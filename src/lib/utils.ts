export { cn } from "cn"

/** Turns any text into a URL slug: "Hello, World 2026!" -> "hello-world-2026". */
export function slugify(text: string): string {
  return text
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}
